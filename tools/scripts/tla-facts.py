#!/usr/bin/env python3
"""Writes prolog/extracted/tla_facts.pl from GuardOrder in ApprovalCore.tla
(C-2t). With --check, fails if the checked-in file differs instead.

usage: tla-facts.py <project-dir> [--check]
"""
import re
import sys

OPS = {"add": "add_principal", "revoke": "revoke_key", "request": "request_action",
       "approve": "approve", "reject": "reject"}

proj = sys.argv[1]
tla = open(f"{proj}/tla/ApprovalCore.tla").read()
body = re.search(r"GuardOrder == \[(.*?)\n\]", tla, re.S).group(1)
out = ["%% GENERATED by tools/scripts/tla-facts.py from GuardOrder in tla/ApprovalCore.tla. Do not edit.\n"]
for op, seq in re.findall(r"(\w+)\s*\|->\s*<<(.*?)>>", body, re.S):
    errs = re.findall(r'"(\w+)"', seq)
    out.append(f"tla_guard_order({OPS[op]}, [{', '.join(repr(e) for e in errs)}]).\n")
text = "".join(out)
path = f"{proj}/prolog/extracted/tla_facts.pl"
if "--check" in sys.argv:
    have = open(path).read() if __import__("os").path.exists(path) else ""
    if have != text:
        sys.exit(f"{path} is stale: run tools/scripts/tla-facts.py {proj}")
else:
    open(path, "w").write(text)
